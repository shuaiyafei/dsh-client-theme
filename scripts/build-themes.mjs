#!/usr/bin/env node
/** Build self-contained client bundles with Node.js; no third-party tooling. */
import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const runtime = (await fs.readFile(path.join(root, "reference/shared/runtime.js"), "utf8"))
	.replace(/^export function /m, "function ");
const boot = await fs.readFile(path.join(root, "reference/shared/boot.html"), "utf8");
const prepared = [];
const variants = (await fs.readdir(path.join(root, "reference"), { withFileTypes: true }))
	.filter((entry) => entry.isDirectory() && entry.name !== "shared")
	.map((entry) => entry.name)
	.sort();

for (const variant of variants) {
	const directory = path.join(root, "reference", variant);
	const source = path.join(directory, "theme");
	const config = JSON.parse(await fs.readFile(path.join(source, "config.json"), "utf8"));
	const palette = JSON.parse(await fs.readFile(path.join(source, "tokens.json"), "utf8"));
	const packageJson = JSON.parse(await fs.readFile(path.join(directory, "package.json"), "utf8"));
	if (config.id !== packageJson.name || !/^[a-z0-9-]+$/.test(config.id)) {
		throw new Error(`${variant}: config.id must match the package name`);
	}
	if (!Number.isFinite(config.syncTarget) || config.syncTarget < 0 || config.syncTarget > 100 ||
		!Number.isFinite(config.bootScale) || config.bootScale <= 0) {
		throw new Error(`${variant}: invalid syncTarget or bootScale`);
	}
	for (const [, name] of boot.matchAll(/\{\{(\w+)\}\}/g)) {
		if (!Object.hasOwn(config, name) || !["string", "number"].includes(typeof config[name])) {
			throw new Error(`${variant}: missing or invalid boot field ${name}`);
		}
	}
	for (const [name, value] of Object.entries(palette)) {
		if (!name.startsWith("--") || typeof value !== "string" || !value.trim()) {
			throw new Error(`${variant}: invalid token ${name}`);
		}
	}
	const image = await fs.readFile(path.join(source, "cover.jpg"));
	if (image.subarray(0, 3).toString("hex") !== "ffd8ff") {
		throw new Error(`${variant}: cover.jpg must contain a JPEG image`);
	}
	const cssSource = await fs.readFile(path.join(source, "skin.css"), "utf8");
	if (cssSource.split("__DSH_THEME_COVER__").length !== 2) {
		throw new Error(`${variant}: skin.css must contain exactly one cover placeholder`);
	}
	const css = cssSource.replace("__DSH_THEME_COVER__", `data:image/jpeg;base64,${image.toString("base64")}`);
	const bundle = `// Generated by scripts/build-themes.mjs. Edit theme/ and reference/shared/.\n` +
		`window.__ModuleLoader__.load({\n  id: ${JSON.stringify(config.id)},\n  factory: () => {\n` +
		runtime + `\n    return createThemePlugin(\n` +
		[config, palette, css, boot].map((value) => `      ${JSON.stringify(value)}`).join(",\n") +
		`\n    );\n  }\n});\n`;
	// Parse the generated program before replacing either distributable.
	new vm.Script(bundle, { filename: `${config.id}/lib/client.js` });
	prepared.push({ directory, bundle, id: config.id });
}

for (const { directory, bundle, id } of prepared) {
	const destination = path.join(directory, "lib/client.js");
	const previous = await fs.readFile(destination, "utf8").catch((error) => {
		if (error.code !== "ENOENT") throw error;
		return null;
	});
	if (previous === bundle) {
		console.log(`Unchanged ${id}`);
		continue;
	}
	const temporary = path.join(directory, "lib", `.client-${process.pid}.tmp`);
	try {
		await fs.writeFile(temporary, bundle, { flag: "wx" });
		await fs.rename(temporary, destination);
	} finally {
		await fs.rm(temporary, { force: true });
	}
	console.log(`Built ${id}: ${Buffer.byteLength(bundle).toLocaleString("en-US")} bytes`);
}
